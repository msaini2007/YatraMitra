export function translate(language: Language, text: string): string {
  if (language !== 'हिन्दी') return text
  if (hindiText[text]) return hindiText[text]

  const planned = text.match(/^(\d+) attraction(s)? planned$/)
  if (planned) return `योजना में ${planned[1]} ${planned[1] === '1' ? 'पर्यटन स्थल' : 'पर्यटन स्थल'}`

  const itineraryDays = text.match(/^(\d+) itinerary day(s)? from selected dates$/)
  if (itineraryDays) return `चुनी गई तारीखों के अनुसार ${itineraryDays[1]} दिन की यात्रा योजना`

  const regeneratedDay = text.match(/^Day (\d+) regenerated(?: by swapping attractions with another day)?\.$/)
  if (regeneratedDay) return text.includes('by swapping attractions with another day')
    ? `दिन ${regeneratedDay[1]} के लिए दूसरे दिन के स्थलों की अदला-बदली की गई`
    : `दिन ${regeneratedDay[1]} की योजना फिर से बनाई गई`

  const overBudget = text.match(/^Over budget by (.+)$/)
  if (overBudget) return `बजट से अधिक: ${overBudget[1]}`

  const remainingBudget = text.match(/^Remaining budget: (.+)$/)
  if (remainingBudget) return `बजट में शेष: ${remainingBudget[1]}`

  const routeBudget = text.match(/^Estimated road-route segment rate for (.+); not a fare quote\.$/)
  if (routeBudget) return `${translate(language, routeBudget[1])} के अनुमानित सड़क मार्ग का खर्च; यह किराये का भाव नहीं है।`

  const transitBudget = text.match(/^Planning estimate for (.+); no live fare or timetable data\.$/)
  if (transitBudget) return `${translate(language, transitBudget[1])} के लिए बजट अनुमान; लाइव किराया या समय-सारणी उपलब्ध नहीं है।`

  const accommodationBudget = text.match(/^(.+) preference using sample rates; not live quotes\.$/)
  if (accommodationBudget) return `${translate(language, accommodationBudget[1])} की पसंद के अनुसार नमूना दरें; यह लाइव भाव नहीं है।`

  const accepted = text.match(/^(.+) accepted$/)
  if (accepted) return `${accepted[1]} ने अनुरोध स्वीकार किया`

  const addAttraction = text.match(/^Add another (.+) attraction$/)
  if (addAttraction) return `${addAttraction[1]} का एक और स्थल जोड़ें`

  const savedCount = text.match(/^(\d+) saved destinations$/)
  if (savedCount) return `सहेजे गए पर्यटन स्थल: ${savedCount[1]}`

  const itineraryCount = text.match(/^(\d+) saved itineraries$/)
  if (itineraryCount) return `सहेजी गई यात्रा योजनाएँ: ${itineraryCount[1]}`

  const resetLink = text.match(/^Demo reset link sent to (.+)$/)
  if (resetLink) return `डेमो पासवर्ड रीसेट लिंक ${resetLink[1]} पर भेजा गया`

  const foodIdeas = text.match(/^Food ideas: (.+)\. These are dish recommendations, not verified restaurant listings\.$/)
  if (foodIdeas) return `भोजन के सुझाव: ${foodIdeas[1]}। ये व्यंजनों के सुझाव हैं, सत्यापित रेस्तराँ की सूची नहीं।`

  const route = text.match(/^OpenStreetMap driving route: (.+) km, about (.+) without live traffic\.(.*)$/)
  if (route) {
    const duration = translateDuration(route[2])
    return `OpenStreetMap सड़क मार्ग: ${route[1]} किमी, अनुमानित समय ${duration}; लाइव ट्रैफ़िक शामिल नहीं है।${route[3] ? ` ${translate(language, route[3].trim())}` : ''}`
  }

  const routeFailure = text.match(/^Driving route unavailable(?: for the final scheduled stops| after this edit)?: (.+?)(?: The itinerary is still usable; route distance and time are not estimated\.| No route distance or travel time is shown\.| No route distance or travel time is estimated\.)$/)
  if (routeFailure) return `ड्राइविंग मार्ग उपलब्ध नहीं है: ${routeFailure[1]} ${text.endsWith('The itinerary is still usable; route distance and time are not estimated.') ? hindiText['The itinerary is still usable; route distance and time are not estimated.'] : text.endsWith('No route distance or travel time is estimated.') ? hindiText['No route distance or travel time is estimated.'] : hindiText['No route distance or travel time is shown.']}`

  const duration = translateDuration(text)
  if (duration !== text) return duration

  if (text.startsWith('Could not save this trip: ')) return `${hindiText['Could not save this trip:']} ${text.slice('Could not save this trip: '.length)}`
  if (text.startsWith('Could not remove this saved trip: ')) return `${hindiText['Could not remove this saved trip:']} ${text.slice('Could not remove this saved trip: '.length)}`
  if (text.startsWith('No alternative listed attractions are available for ')) return `${hindiText['No alternative listed attractions are available for']} ${text.slice('No alternative listed attractions are available for '.length)}`

  return text
}

function translateDuration(text: string) {
  const clockDuration = text.match(/^(\d+)\s*hr(?:\s+(\d+)\s*min)?$/)
  if (clockDuration) {
    const hours = clockDuration[1] === '1' ? 'घंटा' : 'घंटे'
    return `${clockDuration[1]} ${hours}${clockDuration[2] ? ` ${clockDuration[2]} मिनट` : ''}`
  }
  const minutes = text.match(/^(\d+)\s*min$/)
  if (minutes) return `${minutes[1]} मिनट`

  const visitDuration = text.match(/^(\d+)(?:-(\d+))? hours?$/)
  if (visitDuration) return visitDuration[2]
    ? `${visitDuration[1]}–${visitDuration[2]} घंटे`
    : `${visitDuration[1]} ${visitDuration[1] === '1' ? 'घंटा' : 'घंटे'}`

  if (/^\d{1,2}:\d{2}\s*(AM|PM)\s*-\s*\d{1,2}:\d{2}\s*(AM|PM)$/i.test(text)) {
    return text.replace(/\bAM\b/gi, 'पूर्वाह्न').replace(/\bPM\b/gi, 'अपराह्न')
  }
  if (/^Sunrise\s*-\s*\d{1,2}:\d{2}\s*PM$/i.test(text)) {
    return text.replace(/^Sunrise/i, 'सूर्योदय').replace(/\bPM\b/i, 'अपराह्न')
  }
  if (/^Sunrise\s*-\s*\d{1,2}:\d{2}\s*AM$/i.test(text)) {
    return text.replace(/^Sunrise/i, 'सूर्योदय').replace(/\bAM\b/i, 'पूर्वाह्न')
  }
  if (text === '24 hours') return '24 घंटे'
  return text
}

export function localizedContent(
  language: Language,
  kind: ContentKind,
  id: string,
  field: ContentField,
  fallback: string,
) {
  return language === 'हिन्दी' ? hindiContent[kind][id]?.[field] ?? fallback : fallback
}
